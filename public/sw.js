// Service worker VenuePass.
// Sengaja TIDAK meng-cache data/API: aplikasi online-first (PRD §14), hasil scan
// tidak boleh pernah berasal dari cache. Saat offline, navigasi halaman diganti
// dengan halaman pemberitahuan /offline.html.
const OFFLINE_CACHE = "venuepass-offline-v1";
const OFFLINE_URL = "/offline.html";

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(OFFLINE_CACHE).then((cache) => cache.add(OFFLINE_URL)));
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== OFFLINE_CACHE).map((k) => caches.delete(k))),
    ),
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  if (event.request.mode !== "navigate") return;
  event.respondWith(fetch(event.request).catch(() => caches.match(OFFLINE_URL)));
});
